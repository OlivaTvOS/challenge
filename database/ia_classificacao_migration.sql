-- Migracao pontual da tabela de historico dos modelos de IA.
-- Executar no schema Oracle utilizado pela API Java (SQL Developer > Run Script/F5).
-- Nao remove dados nem recria tabelas existentes.

SET SERVEROUTPUT ON;

BEGIN
    EXECUTE IMMEDIATE
        'CREATE SEQUENCE IA_CLASSIFICACAO_ID_SEQ
         MINVALUE 1 MAXVALUE 9999999999999999999999999999
         INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER NOCYCLE';
    DBMS_OUTPUT.PUT_LINE('Sequence IA_CLASSIFICACAO_ID_SEQ criada.');
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE = -955 THEN
            DBMS_OUTPUT.PUT_LINE('Sequence IA_CLASSIFICACAO_ID_SEQ ja existe.');
        ELSE
            RAISE;
        END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE q'~
        CREATE TABLE IA_CLASSIFICACAO (
            ID_CLASSIFICACAO NUMBER NOT NULL,
            ID_USUARIO NUMBER NOT NULL,
            MODELO VARCHAR2(30) NOT NULL,
            PERFIL_PREVISTO VARCHAR2(80),
            CLUSTER_ID NUMBER(3,0),
            CONFIANCA NUMBER(6,5),
            PONTOS_ESTIMADOS NUMBER(10,2),
            MISSOES_RECICLAGEM NUMBER(10,0) DEFAULT 0 NOT NULL,
            MISSOES_MOBILIDADE NUMBER(10,0) DEFAULT 0 NOT NULL,
            MISSOES_AGUA NUMBER(10,0) DEFAULT 0 NOT NULL,
            MISSOES_ENERGIA NUMBER(10,0) DEFAULT 0 NOT NULL,
            MISSOES_NATUREZA NUMBER(10,0) DEFAULT 0 NOT NULL,
            MISSOES_CONSUMO NUMBER(10,0) DEFAULT 0 NOT NULL,
            TAXA_CONCLUSAO NUMBER(5,4) DEFAULT 0 NOT NULL,
            VERSAO_MODELO VARCHAR2(50) NOT NULL,
            DATA_CLASSIFICACAO DATE DEFAULT SYSDATE NOT NULL,
            CONSTRAINT PK_IA_CLASSIFICACAO PRIMARY KEY (ID_CLASSIFICACAO),
            CONSTRAINT FK_IA_CLASSIFICACAO_USUARIO
                FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO) ON DELETE CASCADE,
            CONSTRAINT CK_IA_CLASSIFICACAO_MODELO
                CHECK (MODELO IN ('KMEANS', 'RANDOM_FOREST', 'LINEAR_REGRESSION')),
            CONSTRAINT CK_IA_CLASSIFICACAO_CONFIANCA
                CHECK (CONFIANCA IS NULL OR (CONFIANCA >= 0 AND CONFIANCA <= 1)),
            CONSTRAINT CK_IA_CLASSIFICACAO_TAXA
                CHECK (TAXA_CONCLUSAO >= 0 AND TAXA_CONCLUSAO <= 1)
        )
    ~';
    DBMS_OUTPUT.PUT_LINE('Tabela IA_CLASSIFICACAO criada.');
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE = -955 THEN
            DBMS_OUTPUT.PUT_LINE('Tabela IA_CLASSIFICACAO ja existe; sem alteracoes.');
        ELSE
            RAISE;
        END IF;
END;
/

DECLARE
    v_maior_id NUMBER;
    v_proximo_id NUMBER;
BEGIN
    SELECT NVL(MAX(ID_CLASSIFICACAO), 0)
    INTO v_maior_id
    FROM IA_CLASSIFICACAO;

    LOOP
        SELECT IA_CLASSIFICACAO_ID_SEQ.NEXTVAL
        INTO v_proximo_id
        FROM DUAL;

        EXIT WHEN v_proximo_id > v_maior_id;
    END LOOP;

    DBMS_OUTPUT.PUT_LINE(
        'Sequence sincronizada. Proximo ID disponivel: ' || (v_proximo_id + 1)
    );
END;
/

BEGIN
    EXECUTE IMMEDIATE
        'CREATE INDEX IX_IA_CLASSIFICACAO_USUARIO
         ON IA_CLASSIFICACAO (ID_USUARIO, DATA_CLASSIFICACAO)';
    DBMS_OUTPUT.PUT_LINE('Indice IX_IA_CLASSIFICACAO_USUARIO criado.');
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE = -955 THEN
            DBMS_OUTPUT.PUT_LINE('Indice IX_IA_CLASSIFICACAO_USUARIO ja existe.');
        ELSE
            RAISE;
        END IF;
END;
/

CREATE OR REPLACE TRIGGER IA_CLASSIFICACAO_ID_TRG
BEFORE INSERT ON IA_CLASSIFICACAO
FOR EACH ROW
WHEN (NEW.ID_CLASSIFICACAO IS NULL)
BEGIN
    :NEW.ID_CLASSIFICACAO := IA_CLASSIFICACAO_ID_SEQ.NEXTVAL;
END;
/

COMMIT;

-- Conferencia final: deve retornar uma linha.
